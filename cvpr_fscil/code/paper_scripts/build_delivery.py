from pathlib import Path
import hashlib,json,re,subprocess,tempfile,zipfile
import fitz
from validate_cvpr import validate,MAIN_STEM
H=Path(__file__).resolve().parent
sha=lambda data:hashlib.sha256(data).hexdigest()
v=validate()
names={'draw_framework_drawio.py','framework_drawio.drawio','framework_drawio.svg','figure_assets/illustrative_images.txt','main.tex','supplementary.tex','preamble.tex','cvpr.sty','ieeenat_fullname.bst','references.bib','main.bbl','supplementary.bbl'}
names.update(p.relative_to(H).as_posix() for p in (H/'figure_assets').glob('*.png'))
names.update(p.relative_to(H).as_posix() for p in (H/'experiments').glob('*.md'))
names.update(['softmax_readout/summary.json','softmax_readout/report.md'])
names.update(['cross_encoder/summary.json','cross_encoder/report.md','shrinkage/summary.json',
              'shrinkage/report.md','shrinkage/cardinality_diagnostic.json'])
names.update(p.relative_to(H).as_posix() for p in (H/'revision_evidence').glob('*.json'))
names.update(['prospective/summary.json','prospective_validation.json','tuned_no_fallback.json','tnorm_control.json'])
names.update(['followup_validation.json','followup/summary.json','followup/statistical_audit.json','followup/router_l14.json','followup/router_b32.json'])
names.update(['gate_calibration/summary.json','gate_calibration/report.md'])
names.update(['rn50/summary.json','rn50/report.md','cardinality_rule/summary.json','cardinality_rule/report.md'])
for stem in ['main','supplementary']:
    artifact=MAIN_STEM if stem=='main' else stem
    for line in (H/f'{artifact}.fls').read_text(errors='replace').splitlines():
        if not line.startswith('INPUT '):continue
        raw=line[6:].strip();p=Path(raw)
        if not p.is_absolute():p=H/p
        try:rel=p.resolve().relative_to(H.resolve())
        except ValueError:continue
        if rel.suffix in ['.tex','.pdf','.bib','.sty','.bst','.bbl']:
            names.add(rel.as_posix())
assert not any(n.startswith('template_provenance/') for n in names)
assert 'main.pdf' not in names and 'supplementary.pdf' not in names
files={n:(H/n).read_bytes() for n in sorted(names)}
instructions='''CVPR 2027 anonymous LaTeX source

Compile main.tex first, then supplementary.tex, using latexmk -pdf.
Main scientific content and disclosure occupy at most 8 pages; references follow.
The supplement imports main.aux, generated by compiling main.tex.
cvpr.sty and ieeenat_fullname.bst are unchanged official CVPR 2027 files.
The official 2027 template does not print a Paper ID. This package does not perform OpenReview enrollment or submission.
'''
files['BUILD.txt']=instructions.encode()
for n,data in files.items():
    if n.endswith(('.tex','.bib','.bbl','.txt','.md','.json')):
        lower=data.decode('utf-8',errors='ignore').lower()
        assert not any(w in lower for w in ['junyi zhang','shandong university','cheerssom']),n
        # Match a complete account/path token, not digits inside measured decimals.
        assert not re.search(r'(?<![a-z0-9])32488(?![a-z0-9])',lower),n
        assert 'kbs_' not in lower and 'reviewer_revision' not in lower,n
    if n.endswith('.pdf'):
        with fitz.open(stream=data,filetype='pdf') as d:
            inspect=(str(d.metadata)+'\n'+'\n'.join(p.get_text() for p in d)).lower()
            assert not any(w in inspect for w in ['junyi zhang','shandong university','cheerssom','32488']),n
def write_zip(path,payload):
    hashes={n:sha(b) for n,b in payload.items()}
    with zipfile.ZipFile(path,'w',zipfile.ZIP_DEFLATED) as z:
        for n,b in payload.items():z.writestr(n,b)
        z.writestr('file_hashes.json',json.dumps(hashes,indent=2))
    with zipfile.ZipFile(path) as z:
        assert z.testzip() is None
        for n,h in hashes.items():assert sha(z.read(n))==h
    return hashes
source=H/'cvpr2027_source.zip';write_zip(source,files)
# Compile exclusively from the archive, outside the project tree.
with tempfile.TemporaryDirectory(prefix='cvpr2027-clean-') as tmp:
    root=Path(tmp)
    with zipfile.ZipFile(source) as z:z.extractall(root)
    package={}
    for stem in ['main','supplementary']:
        proc=subprocess.run(['latexmk','-pdf','-interaction=nonstopmode','-halt-on-error',stem+'.tex'],
                            cwd=root,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,timeout=180)
        assert proc.returncode==0,proc.stdout[-3000:]
        log=(root/f'{stem}.log').read_text(errors='replace')
        assert not any(x in log for x in ['Overfull','LaTeX Warning:','Package natbib Warning:','! ']),stem
        with fitz.open(root/f'{stem}.pdf') as d:
            assert len(d)==v['documents'][stem]['pdf_pages']
            package[stem]={'pages':len(d),'clean_compile':True}
package['source_files']=len(files)
package['anonymous_source_scan']=True
(H/'package_validation.json').write_text(json.dumps(package,indent=2)+'\n')
